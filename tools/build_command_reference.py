"""Generate ``docs/reference/commands.md`` from the application's own menus.

The page lists every built-in menu command -- its menu path, default shortcut,
and the summary, parameters, inputs and outputs declared in
``minflux_viewer/ui/common/command_meta.py`` -- so the reference cannot drift
from the program: ``tests/test_docs_command_reference.py`` fails when they
disagree.

    python tools/build_command_reference.py           # rewrite the page
    python tools/build_command_reference.py --check   # exit 1 if it is stale

The main window is built off-screen with default preferences that are never
saved, and only commands implemented inside the ``minflux_viewer`` package are
listed, so a user's own plugins never reach the page.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "reference" / "commands.md"

_UNAVAILABLE_PREFIX = "Not implemented"

_HEADER = """\
# Command reference

<!-- Generated by tools/build_command_reference.py from the application's menus
     and minflux_viewer/ui/common/command_meta.py. Do not edit by hand. -->

Every built-in menu command, in menu order, with its default keyboard shortcut
(change shortcuts in *Edit › Preferences › Shortcuts*). Any command can also be
found by typing a few letters of its name, menu or purpose in the search field
at the right of the toolbar, or in *Help › Command Finder*.

Plugins installed by the user are not listed here; see the
[scripting and plugin API](../scripting-api.md).
"""


def _meta_by_action(window) -> dict[int, object]:
    """QAction id -> its ``CommandMeta`` (attribute keys and the loop-built groups)."""
    from minflux_viewer.ui.common.command_meta import COMMAND_META

    found: dict[int, object] = {}
    for key, meta in COMMAND_META.items():
        if key.startswith("_"):
            continue
        action = getattr(window, key, None) or getattr(window._ui, key, None)
        if action is not None:
            found[id(action)] = meta
    for group_key, menu_attr in (("_roi_convert", "menuRoiConvert"), ("_roi_fit", "menuRoiFit")):
        meta = COMMAND_META.get(group_key)
        menu = getattr(window, menu_attr, None)
        if meta is None or menu is None:
            continue
        for action in menu.actions():
            if not action.isSeparator() and action.menu() is None:
                found[id(action)] = meta
    return found


def _group_actions(window) -> list:
    """Leaf actions of the menus whose commands are built in a loop."""
    out = []
    for menu_attr in ("menuRoiConvert", "menuRoiFit"):
        menu = getattr(window, menu_attr, None)
        if menu is not None:
            out += [a for a in menu.actions() if not a.isSeparator() and a.menu() is None]
    return out


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _description(entry, meta) -> str:
    """The command's summary; a plugin (no metadata) describes itself in its tooltip."""
    summary = getattr(meta, "summary", "") if meta is not None else ""
    if summary:
        return summary.strip()
    tip = str(entry.action.toolTip() or "").strip()
    return "" if tip.replace("&", "") == entry.text else tip


def _render_command(entry, meta) -> list[str]:
    lines = [f"### {entry.text}", ""]
    facts = [f"*{entry.path} › {entry.text}*"]
    if entry.shortcut:
        facts.append(f"shortcut **{entry.shortcut}**")
    lines.append(" · ".join(facts))
    lines.append("")
    summary = _description(entry, meta)
    if summary:
        lines += [summary, ""]
    params = getattr(meta, "params", ()) if meta is not None else ()
    if params:
        lines += ["| Parameter | Default | Unit | Meaning |", "|---|---|---|---|"]
        for p in params:
            default = "" if p.default is None else p.default
            lines.append(f"| `{_cell(p.name)}` | {_cell(default)} | {_cell(p.unit)} "
                         f"| {_cell(p.description)} |")
        lines.append("")
    for label, items in (("Inputs", getattr(meta, "inputs", ()) if meta else ()),
                         ("Outputs", getattr(meta, "outputs", ()) if meta else ())):
        if items:
            lines += [f"{label}: " + "; ".join(str(i) for i in items) + ".", ""]
    return lines


def _render_group(entries, meta) -> list[str]:
    """Variants built in a loop share one description (ROI Convert, ROI Fit)."""
    path = entries[0].path
    lines = [f"### {path.split(' › ')[-1]}", "", f"*{path} › …*", ""]
    summary = _description(entries[0], meta)
    if summary:
        lines += [summary, ""]
    lines += ["Variants: " + ", ".join(f"*{e.text}*" for e in entries) + ".", ""]
    return lines


def build_markdown(window) -> str:
    """The complete page for an already-built main window."""
    from minflux_viewer.ui.tools.command_finder import collect_commands

    metas = _meta_by_action(window)
    sections: dict[str, list[str]] = {}
    unavailable: dict[str, list[str]] = {}
    order: list[str] = []
    grouped = {id(a) for a in _group_actions(window)}
    pending: list = []

    def flush(top: str) -> None:
        if pending:
            sections[top] += _render_group(pending, metas.get(id(pending[0].action)))
            pending.clear()

    entries = collect_commands(window.menuBar())
    # The Plugins menu follows registration order, which depends on what was
    # imported first; list plugins alphabetically so the page is reproducible.
    plugins = sorted((e for e in entries if e.path.split(" › ")[0] == "Plugins"),
                     key=lambda e: (e.path, e.text.lower()))
    others = [e for e in entries if e.path.split(" › ")[0] != "Plugins"]
    at = next((i for i, e in enumerate(entries) if e.path.split(" › ")[0] == "Plugins"),
              len(others))
    entries = others[:at] + plugins + others[at:]
    for entry in entries:
        if not entry.source.startswith("minflux_viewer/"):
            continue                       # user plugins, file lists
        top = entry.path.split(" › ")[0]
        if top not in sections:
            sections[top] = []
            unavailable[top] = []
            order.append(top)
        if id(entry.action) in grouped:
            if pending and pending[0].path != entry.path:
                flush(top)
            pending.append(entry)
            continue
        flush(top)
        tip = str(entry.action.toolTip() or "")
        if not entry.enabled and tip.startswith(_UNAVAILABLE_PREFIX):
            unavailable[top].append(f"*{entry.path} › {entry.text}*")
            continue
        sections[top] += _render_command(entry, metas.get(id(entry.action)))
    if pending:
        flush(pending[0].path.split(" › ")[0])

    lines = [_HEADER]
    lines += ["## Menus", ""] + [f"- [{top}](#{top.lower().replace(' ', '-')})"
                                 for top in order] + [""]
    for top in order:
        lines += [f"## {top}", ""] + sections[top]
        if unavailable[top]:
            lines += ["Shown in the menu but not available in this version: "
                      + ", ".join(unavailable[top]) + ".", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def _isolated_window():
    """A main window on default, never-saved preferences."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from PyQt6.QtWidgets import QApplication

    app = QApplication.instance() or QApplication(sys.argv[:1])
    from minflux_viewer.core import app_state as _app_state

    _app_state.AppState._load_prefs = lambda self: _app_state.default_prefs()
    _app_state.AppState.save_prefs = lambda self, *a, **k: None
    from minflux_viewer.ui.main_window import MainWindow

    state = _app_state.AppState()
    state.prefs.setdefault("data", {}).update({"show_data_info": False, "show_render": False})
    state.prefs.setdefault("plugin", {})["scan_user_dir"] = False
    return app, MainWindow(state)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="report whether the page is current; do not write it")
    args = parser.parse_args(argv)
    _app, window = _isolated_window()
    text = build_markdown(window)
    current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
    if args.check:
        stale = current != text
        print(f"{PAGE.relative_to(ROOT)} is {'STALE' if stale else 'current'}.")
        code = 1 if stale else 0
    else:
        PAGE.parent.mkdir(parents=True, exist_ok=True)
        PAGE.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {PAGE.relative_to(ROOT)} ({text.count(chr(10) + '### ')} commands)")
        code = 0
    sys.stdout.flush()
    # Leave without Qt teardown: closing the window would run its closeEvent.
    os._exit(code)


if __name__ == "__main__":
    raise SystemExit(main())
